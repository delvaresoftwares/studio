import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { loadBlogs } from './load-blogs.mjs';

/**
 * Generates src/lib/blog-summaries.ts from src/lib/blogs.ts.
 *
 * Client components (cards, filters, the homepage journal section and the
 * founder page) only need card-level fields. Importing the full dataset pulled
 * every article body into a shared client chunk, so this writes out the slim
 * projection instead.
 *
 * Run after editing src/lib/blogs.ts:
 *   npm run gen:blog-summaries
 *   npm run check:blog-summaries   (CI guard; exits 1 if stale)
 */

const OUT = resolve(process.cwd(), 'src/lib/blog-summaries.ts');
const SUMMARY_FIELDS = [
    'slug',
    'title',
    'subtitle',
    'excerpt',
    'metaDescription',
    'category',
    'date',
    'updated',
    'image',
    'imageAlt',
    'ogImage',
    'tags',
    'readingTime',
    'featured',
    'serviceSlug',
    'serviceTitle',
];
const AUTHOR_FIELDS = ['name', 'role', 'avatar', 'profileUrl', 'sameAs'];

const { blogs } = loadBlogs();

const summaries = blogs.map((post) => {
    const summary = {};
    for (const field of SUMMARY_FIELDS) summary[field] = post[field];
    summary.author = Object.fromEntries(
        AUTHOR_FIELDS.map((field) => [field, post.author[field]])
    );
    return summary;
});

const generated = `// AUTO-GENERATED by src/scripts/gen-blog-summaries.mjs — do not edit by hand.
// Run \`npm run gen:blog-summaries\` after changing src/lib/blogs.ts.

import type { BlogSummary } from './blog-types';

export const blogSummaries: BlogSummary[] = ${JSON.stringify(summaries, null, 4)};

export const getFeaturedSummary = () =>
    blogSummaries.find((post) => post.featured) ?? blogSummaries[0];

export const getSummaryBySlug = (slug: string) =>
    blogSummaries.find((post) => post.slug === slug);

export const getRelatedSummaries = (post: BlogSummary, limit = 2) =>
    blogSummaries
        .filter((candidate) => candidate.slug !== post.slug)
        .map((candidate) => ({
            post: candidate,
            score:
                (candidate.category === post.category ? 2 : 0) +
                candidate.tags.filter((tag) => post.tags.includes(tag)).length,
        }))
        .sort((a, b) => b.score - a.score)
        .slice(0, limit)
        .map((entry) => entry.post);

export const blogTopics = [
    'All',
    ...Array.from(new Set(blogSummaries.map((post) => post.category))),
];
`;

const current = (() => {
    try {
        return readFileSync(OUT, 'utf8');
    } catch {
        return null;
    }
})();

if (process.argv.includes('--check')) {
    if (current !== generated) {
        console.error(
            'src/lib/blog-summaries.ts is out of date. Run: npm run gen:blog-summaries'
        );
        process.exit(1);
    }
    console.log(`blog summaries up to date (${summaries.length} posts)`);
} else {
    writeFileSync(OUT, generated);
    console.log(`wrote src/lib/blog-summaries.ts (${summaries.length} posts)`);
}
